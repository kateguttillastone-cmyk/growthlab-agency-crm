export interface Demo {
  leads: Array<DemoLead & { email_addr: string | null; phone: string }>;
}

/** Décline une adresse en « base+étiquette@domaine » : toutes arrivent dans la même boîte. */
export function plusAddress(base: string, tag: string): string {
  const [local, domain] = base.toLowerCase().split("@");
  if (!local || !domain) throw new Error(`Adresse invalide : ${base}`);
  return `${local.split("+")[0]}+${tag}@${domain}`;
}

/** Numéro au format international ; un numéro malgache (03x) est reconnu, sinon on suppose la France. */
export function toInternational(raw: string): string {
  const d = raw.replace(/\D/g, "");
  if (raw.trim().startsWith("+")) return `+${d}`;
  if (/^03[2-4789]\d{7}$/.test(d)) return `+261${d.slice(1)}`;
  if (d.startsWith("0") && d.length === 10) return `+33${d.slice(1)}`;
  throw new Error(`Numéro non reconnu : ${raw}`);
}

export function buildDemo(input: { emails: string[]; phones: string[] }): Demo {
  const phones = input.phones.map(toInternational);
  return {
    leads: DEMO_LEADS.map((l, i) => ({
      ...l,
      email_addr: l.contact ? plusAddress(input.emails[i % input.emails.length] as string, l.tag) : null,
      phone: phones[i % phones.length] as string,
    })),
  };
}
